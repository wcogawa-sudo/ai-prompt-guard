// Builds extension/src/words.js: everyday English words, used by the name
// detector to tell a surname ("Okafor") from an ordinary word ("tomorrow")
// after a known first name. Source: the system cracklib word list.
// Names from names.js are removed so they stay unfamiliar.
//   node scripts/build-words.js [/usr/share/dict/cracklib-small]
const fs = require("node:fs");
const path = require("node:path");

const src = process.argv[2] || "/usr/share/dict/cracklib-small";
const names = require("../extension/src/names.js");
// Chat shorthand, brands and tech words people type right after a name
// ("ask john tmrw", "john linkedin post"); not in cracklib.
const EXTRA = `tmrw tmr tomoz tdy thx thnx thanx ty tx pls plz pkz asap lol lmao omg btw fyi tbh idk imo imho
  ok okay k kk np nvm omw brb ttyl gm gn wrt abt bc cos cuz coz msg msgs txt dm pm ppl tho thru u ur yr
  wanna gonna gotta lemme aint yeah yep yup nope ya hey hiya cheers sharp lekker eish howzit
  covid email emails emailed inbox calendar meeting zoom teams slack whatsapp telegram signal
  gmail outlook excel word powerpoint onedrive sharepoint dropbox google youtube linkedin facebook
  instagram twitter tiktok chatgpt openai claude copilot gemini github gitlab jira confluence
  sql api apis url urls login logins wifi vpn pdf csv laptop laptops iphone android app apps
  online offline website webinar invoice invoices payslip payroll`;
const keep = new Set(EXTRA.split(/\s+/).filter(Boolean));
for (const raw of fs.readFileSync(src, "utf8").split("\n")) {
  const w = raw.trim();
  if (!/^[a-z]{2,14}$/.test(w)) continue; // no possessives, digits or proper-noun casing
  if (names.first.has(w) || names.last.has(w)) continue;
  keep.add(w);
}
const list = [...keep].sort().join(" ");
const out = `// GENERATED by scripts/build-words.js from ${path.basename(src)}. Do not edit by hand.
// Everyday English words (lowercase). A word NOT in this list right after a
// known first name is treated as an unfamiliar word, i.e. probably a surname.
(function (root) {
  "use strict";
  const words = new Set("${list}".split(" "));
  root.PG = root.PG || {};
  root.PG.words = words;
  if (typeof module !== "undefined" && module.exports) module.exports = words;
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
fs.writeFileSync(path.join(__dirname, "../extension/src/words.js"), out);
console.log(`words.js: ${keep.size} words, ${(out.length / 1024).toFixed(0)} KB`);
